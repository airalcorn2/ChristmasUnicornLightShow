"""Tunable mapping from frequency bands to the unicorn's light groups."""

from __future__ import annotations

import json
from pathlib import Path

BandConfig = tuple[float, float, tuple[int, int, int]]
"""(hz_low, hz_high, (r, g, b) peak color) for one group's frequency band."""

BAND_CONFIG: dict[str, BandConfig] = {
    "Head": (20, 120, (255, 0, 0)),
    "Mane": (120, 300, (255, 90, 0)),
    "Trim": (300, 700, (255, 200, 0)),
    "Hat": (700, 1800, (0, 255, 60)),
    "Horn": (1800, 4500, (0, 160, 255)),
    "Eye": (4500, 8000, (140, 0, 255)),
}
"""Each logical band pulses with the energy in its own frequency range, low
to high, roughly tracing bass -> mids -> treble across the unicorn from body
to head (red -> orange -> yellow -> green -> blue -> violet).

Most of these names are also literal group names (see layout.py), except
"Eye": the physical group lit is "Open Eye" or "Closed Eye" depending on the
current blink state (see equalizer.py's BlinkState), both sharing this one
color/band rather than each having their own. "Mouth" is not a band at all -
the mouth (whichever of "Open Mouth"/"Closed Mouth" matches MOUTH_GATE_BANDS'
current energy, see below) simply mirrors Head's own color and level, rather
than reacting to its own frequency range - see equalizer.py's build_frame().
This intentionally leaves nothing covering roughly 8-16kHz; that range
previously drove a separate, now-removed "Closed Mouth" band.
"""

MOUTH_GATE_BANDS: tuple[str, ...] = ("Trim", "Hat")
"""Which bands' gate_levels (see BandAnalyzer) decide whether the mouth is
open, by their average - not Head/bass, so the mouth tracks singing rather
than the beat. Trim (300-700 Hz) and Hat (700-1800 Hz) sit in vocal
formant/intelligibility range, where sung lyrics show up as energy
regardless of the bass line underneath them."""

SHOW_COLORS_PATH = Path(__file__).resolve().parent / "show_colors.json"
"""Generated by show_colors.py from the real show's rendered .fseq - see
official_band_config()."""


def official_band_config() -> dict[str, BandConfig]:
    """BAND_CONFIG, but with each group's color replaced by its dominant
    color from the actual rendered show (show_colors.py), instead of the
    hand-picked ones above - same frequency band edges throughout.

    Falls back to BAND_CONFIG's own color for any band show_colors.json
    doesn't cover (e.g., the file is stale relative to a BAND_CONFIG
    change). "Eye" has no literal "Eye" entry in show_colors.json (nothing
    called just "Eye" is ever lit in the real show) - it looks up "Open
    Eye" instead, since that's the show's own name for the shape this
    band actually lights, and it's white there. Note that "Horn" cycles
    through many colors in the real show rather than holding one, so its
    "official" color here is just the single most common one, not very
    representative - show_colors.py prints a caveat for any band like this.

    Raises FileNotFoundError if show_colors.json hasn't been generated yet -
    run `python3 show_colors.py` first.
    """
    if not SHOW_COLORS_PATH.exists():
        raise FileNotFoundError(
            f"{SHOW_COLORS_PATH} not found - run `python3 show_colors.py` first"
        )
    with open(SHOW_COLORS_PATH) as f:
        official_colors: dict[str, list[int]] = json.load(f)

    result: dict[str, BandConfig] = {}
    for name, (low_hz, high_hz, default_color) in BAND_CONFIG.items():
        lookup_name = "Open Eye" if name == "Eye" else name
        if lookup_name in official_colors:
            r, g, b = official_colors[lookup_name]
            color = (r, g, b)
        else:
            color = default_color
        result[name] = (low_hz, high_hz, color)
    return result


BLINK_MIN_INTERVAL: float = 3.0
"""Shortest gap between the start of one blink and the next."""
BLINK_MAX_INTERVAL: float = 6.0
"""Longest gap between the start of one blink and the next - randomized
between this and BLINK_MIN_INTERVAL each time, like a natural blink rather
than a fixed metronome."""
BLINK_DURATION: float = 0.15
"""How long the eye stays closed for each blink."""

MOUTH_OPEN_THRESHOLD: float = 0.55
"""MOUTH_GATE_BANDS' average gate level must exceed this for the mouth to
switch to "open" - i.e., "there's singing right now", not merely "not
silent". Tune against real music the same way this was tuned for the
previous bass-gated version: capture gate levels during an actual track and
check where "singing"/"not singing" actually falls, rather than guessing."""
MOUTH_CLOSE_THRESHOLD: float = 0.4
"""MOUTH_GATE_BANDS' average gate level must drop below this to switch back
to "closed". Lower than MOUTH_OPEN_THRESHOLD on purpose (hysteresis): with a
single shared threshold, a gate level hovering right at that line would
flutter open/closed every frame; a gap between the two thresholds makes the
mouth hold its current state until a clean crossing happens."""

SAMPLE_RATE: int = 48000
BLOCK_SIZE: int = 1024
"""Audio samples per analysis frame (FFT window size)."""
FPS: int = 40
"""Pixel-frame send rate."""

ATTACK: float = 0.6
"""Per-band envelope follower rise rate (0-1, higher = faster) - fast so
transients pop."""
RELEASE: float = 0.15
"""Per-band envelope follower fall rate (0-1, higher = faster) - slow
(~400ms to decay 95%) so the *visual brightness* doesn't flicker like
static. Too slow for an on/off gate, though: during continuous bass it can
stay above GATE_RELEASE's threshold the whole time and never visibly
"close" - see GATE_RELEASE."""
GATE_RELEASE: float = 0.6
"""Fall rate for BandAnalyzer.gate_levels, used for binary on/off decisions
like whether the mouth is "open" (see equalizer.py's MOUTH_OPEN_THRESHOLD
and build_frame()) rather than for driving a light's visible brightness.
Equal to ATTACK - i.e., no extra smoothing lag in either direction - so a
gate reflects whether there's bass *right now*, independent of how slowly
RELEASE fades the light itself."""

AGC_DECAY: float = 0.995
"""How slowly each band's automatic-gain ceiling sinks back down after a
loud moment passes. Simple per-band AGC so quiet and loud sources both light
up the full brightness range instead of needing a manually tuned gain
knob."""
MIN_AGC_CEILING: float = 1e-3
"""Floor for the AGC ceiling, to avoid dividing by a near-zero value during
silence."""
NOISE_FLOOR: float = 0.02
"""Normalized band energy below this is treated as off."""

